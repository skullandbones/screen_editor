;==============================================================================
; BEAUTIFY.ASM - Z80 Source Code Beautifier Plugin for SE.COM
; Digital Research CP/M 3 Page-Relocatable (.PRL) & Overlay (.OVL) Format
;
; Formats labels, mnemonics, operands, and comments into aligned columns.
; If BLOCK_ACTIVE != 0: beautifies only lines in selected block.
; If BLOCK_ACTIVE == 0: beautifies entire open document.
; If FMT_ANIMATE != 0: provides animated progress tracking on status bar.
;
; Entry:
;   IX = Pointer to PLUGIN_HOST_API vector
; Returns:
;   A  = 2 (Document modified / redraw screen)
;   CY = 0 (Success)
;==============================================================================

	ORG	0100H

;------------------------------------------------------------------------------
; Standard 3-Entry Jump Table
;------------------------------------------------------------------------------
ENTRY:
	JP	DO_BEAUTIFY_EXECUTE	; +0: Action 0 (Main Execution)
	JP	DO_BEAUTIFY_ABOUT	; +3: Action 1 (About Screen)
	JP	DO_BEAUTIFY_CONFIG	; +6: Action 2 (Config Screen)

;------------------------------------------------------------------------------
; Action 0: Main Execution (Beautify Active Block or Document)
;------------------------------------------------------------------------------
DO_BEAUTIFY_EXECUTE:
	; Verify Host API Magic "SE" (check IX or IY)
	LD	A,(IX+0)
	CP	'S'
	JR	Z,API_OK
	PUSH	IY
	POP	IX
	LD	A,(IX+0)
	CP	'S'
	JP	NZ,INIT_ERR
API_OK:
	LD	A,(IX+1)
	CP	'E'
	JP	NZ,INIT_ERR

	; Save Host API vector pointer
	LD	(HOST_API_PTR),IX

	; Save ACTIVE_LINE_BUF pointer from IX+4
	LD	L,(IX+4)
	LD	H,(IX+5)
	LD	(HOST_ACTIVE_LINE_BUF),HL

	; Save ACTIVE_LINE_LEN pointer from IX+6
	LD	L,(IX+6)
	LD	H,(IX+7)
	LD	(HOST_ACTIVE_LINE_LEN),HL

	; Check if document is empty (DOC_TOTAL_LINES at IX+10)
	LD	L,(IX+10)
	LD	H,(IX+11)
	LD	E,(HL)
	INC	HL
	LD	D,(HL)			; DE = DOC_TOTAL_LINES
	LD	(TOTAL_LINES_VAL),DE
	LD	A,D
	OR	E
	JP	Z,FINISH_NO_CHANGE

	; Read Tab Width from IX+42 and calculate CFG_TAB_MASK
	LD	L,(IX+42)
	LD	H,(IX+43)
	LD	A,(HL)			; Tab width: 4 or 8
	DEC	A			; Mask: 3 or 7
	LD	(CFG_TAB_MASK),A

	; Load configuration from BEAUTIFY.CFG (or defaults)
	CALL	LOAD_PLUGIN_CFG
	LD	IX,(HOST_API_PTR)

	; Check if a block is active (BLOCK_ACTIVE at IX+36)
	LD	L,(IX+36)
	LD	H,(IX+37)
	LD	A,(HL)
	OR	A
	JR	Z,DO_WHOLE_FILE

	; Block is active: read BLOCK_START_ROW (IX+38) and BLOCK_END_ROW (IX+40)
	LD	L,(IX+38)
	LD	H,(IX+39)
	LD	E,(HL)
	INC	HL
	LD	D,(HL)			; DE = BLOCK_START_ROW

	LD	L,(IX+40)
	LD	H,(IX+41)
	LD	C,(HL)
	INC	HL
	LD	B,(HL)			; BC = BLOCK_END_ROW

	; Ensure StartRow (DE) <= EndRow (BC)
	LD	A,D
	CP	B
	JR	C,BLOCK_SORTED
	JR	NZ,BLOCK_SWAP
	LD	A,E
	CP	C
	JR	C,BLOCK_SORTED
	JR	Z,BLOCK_SORTED
BLOCK_SWAP:
	EX	DE,HL
	LD	D,B
	LD	E,C
	LD	B,H
	LD	C,L			; Now DE = min(Start, End), BC = max(Start, End)
BLOCK_SORTED:
	LD	(BEAUTIFY_START_ROW),DE

	; Ensure EndRow (BC) < DOC_TOTAL_LINES
	LD	HL,(TOTAL_LINES_VAL)
	LD	A,B
	CP	H
	JR	C,BLOCK_END_OK
	JR	NZ,BLOCK_CLIP
	LD	A,C
	CP	L
	JR	C,BLOCK_END_OK
BLOCK_CLIP:
	LD	BC,(TOTAL_LINES_VAL)
	DEC	BC
BLOCK_END_OK:
	LD	(BEAUTIFY_END_ROW),BC
	JR	START_LINE_LOOP

DO_WHOLE_FILE:
	LD	HL,0
	LD	(BEAUTIFY_START_ROW),HL
	LD	HL,(TOTAL_LINES_VAL)
	DEC	HL
	LD	(BEAUTIFY_END_ROW),HL

START_LINE_LOOP:
	XOR	A
	LD	(ANY_LINE_MODIFIED),A
	LD	HL,(BEAUTIFY_START_ROW)

BEAUTIFY_ROW_LOOP:
	LD	(CUR_ROW_VAL),HL
	PUSH	HL
	CALL	CALL_HOST_CHECKOUT
	POP	HL

	CALL	BEAUTIFY_LINE_BUFFER

	; Check animation
	LD	A,(FMT_ANIMATE)
	OR	A
	JR	Z,CHECK_ROW_END
	CALL	DO_ANIM_STEP
	JR	C,BEAUTIFY_CANCELLED

CHECK_ROW_END:
	LD	HL,(CUR_ROW_VAL)
	LD	DE,(BEAUTIFY_END_ROW)
	LD	A,H
	CP	D
	JR	NZ,BEAUTIFY_ROW_INC
	LD	A,L
	CP	E
	JR	Z,BEAUTIFY_FINISHED

BEAUTIFY_ROW_INC:
	INC	HL
	JR	BEAUTIFY_ROW_LOOP

BEAUTIFY_CANCELLED:
	LD	DE,STR_MSG_CANCEL
	CALL	CALL_HOST_STATUS
	LD	A,(ANY_LINE_MODIFIED)
	OR	A
	JR	NZ,FINISH_MODIFIED
	JR	FINISH_NO_CHANGE

BEAUTIFY_FINISHED:
	LD	DE,STR_MSG_DONE
	CALL	CALL_HOST_STATUS
	LD	A,2			; A = 2: Document modified / redraw screen
	OR	A			; Clear carry (CY=0)
	RET

FINISH_MODIFIED:
	LD	A,2
	OR	A
	RET

FINISH_NO_CHANGE:
	XOR	A			; A = 0: No changes
	RET

INIT_ERR:
	LD	A,0FFH
	SCF
	RET

;------------------------------------------------------------------------------
; Action 1: Modal About Screen
;------------------------------------------------------------------------------
DO_BEAUTIFY_ABOUT:
	; Verify Host API Magic "SE" (check IX or IY)
	LD	A,(IX+0)
	CP	'S'
	JR	Z,BT_ABT_API_OK
	PUSH	IY
	POP	IX
	LD	A,(IX+0)
	CP	'S'
	JP	NZ,INIT_ERR
BT_ABT_API_OK:
	LD	A,(IX+1)
	CP	'E'
	JP	NZ,INIT_ERR

	LD	(HOST_API_PTR),IX

	LD	HL,BEAUTIFY_ABT_TABLE
	LD	B,12
	LD	C,38
	CALL	RENDER_CENTERED_BOX
	CALL	CALL_HOST_GETKEY

	XOR	A			; A = 0: Clean, document unmodified
	OR	A			; Clear Carry (CY=0)
	RET

;------------------------------------------------------------------------------
; Action 2: Interactive Configuration Screen
;------------------------------------------------------------------------------
DO_BEAUTIFY_CONFIG:
	; Verify Host API Magic "SE" (check IX or IY)
	LD	A,(IX+0)
	CP	'S'
	JR	Z,BT_CFG_API_OK
	PUSH	IY
	POP	IX
	LD	A,(IX+0)
	CP	'S'
	JP	NZ,INIT_ERR
BT_CFG_API_OK:
	LD	A,(IX+1)
	CP	'E'
	JP	NZ,INIT_ERR

	LD	(HOST_API_PTR),IX

	; Load configuration from BEAUTIFY.CFG (or defaults)
	CALL	LOAD_PLUGIN_CFG
	LD	IX,(HOST_API_PTR)

BT_CFG_LOOP:
	; 1. Format Preset
	LD	A,(CFG_PRESET_IDX)
	CP	1
	JR	Z,SET_PRESET_1
	CP	2
	JR	Z,SET_PRESET_2
	LD	HL,STR_PRESET_0
	JR	COPY_PRESET_STR
SET_PRESET_1:
	LD	HL,STR_PRESET_1
	JR	COPY_PRESET_STR
SET_PRESET_2:
	LD	HL,STR_PRESET_2
COPY_PRESET_STR:
	LD	DE,STR_CFG_COLS_VAL
	LD	BC,15
	LDIR

	; 2. Format Mnemonic Case
	LD	A,(FMT_CASE_MNEM)
	CP	1
	JR	Z,SET_MNEM_1
	CP	2
	JR	Z,SET_MNEM_2
	LD	HL,STR_CASE_0
	JR	COPY_MNEM_STR
SET_MNEM_1:
	LD	HL,STR_CASE_1
	JR	COPY_MNEM_STR
SET_MNEM_2:
	LD	HL,STR_CASE_2
COPY_MNEM_STR:
	LD	DE,STR_CFG_MNEM_VAL
	LD	BC,15
	LDIR

	; 3. Format Register Case
	LD	A,(FMT_CASE_OPER)
	CP	1
	JR	Z,SET_OPER_1
	CP	2
	JR	Z,SET_OPER_2
	LD	HL,STR_CASE_0
	JR	COPY_OPER_STR
SET_OPER_1:
	LD	HL,STR_CASE_1
	JR	COPY_OPER_STR
SET_OPER_2:
	LD	HL,STR_CASE_2
COPY_OPER_STR:
	LD	DE,STR_CFG_OPER_VAL
	LD	BC,15
	LDIR

	; 4. Format Animation
	LD	A,(FMT_ANIMATE)
	OR	A
	JR	Z,SET_ANIM_0
	LD	HL,STR_ANIM_1
	JR	COPY_ANIM_STR
SET_ANIM_0:
	LD	HL,STR_ANIM_0
COPY_ANIM_STR:
	LD	DE,STR_CFG_ANIM_VAL
	LD	BC,15
	LDIR

	; Print Config Screen
	LD	HL,BEAUTIFY_CFG_TABLE
	LD	B,10
	LD	C,38
	CALL	RENDER_CENTERED_BOX

	; Wait for input
	CALL	CALL_HOST_GETKEY

	CP	'1'
	JR	Z,BT_TOGGLE_COLS
	CP	'2'
	JR	Z,BT_TOGGLE_MNEM
	CP	'3'
	JR	Z,BT_TOGGLE_OPER
	CP	'4'
	JR	Z,BT_TOGGLE_ANIM
	CP	'Q'
	JR	Z,BT_CFG_SAVE_EXIT
	CP	'q'
	JR	Z,BT_CFG_SAVE_EXIT
	CP	13			; Enter
	JR	Z,BT_CFG_SAVE_EXIT
	CP	27			; ESC
	JR	Z,BT_CFG_DONE
	JP	BT_CFG_LOOP

BT_TOGGLE_COLS:
	LD	A,(CFG_PRESET_IDX)
	INC	A
	CP	3
	JR	C,BT_COLS_OK
	XOR	A
BT_COLS_OK:
	CALL	APPLY_COL_PRESET
	JP	BT_CFG_LOOP

BT_TOGGLE_MNEM:
	LD	A,(FMT_CASE_MNEM)
	INC	A
	CP	3
	JR	C,BT_MNEM_OK
	XOR	A
BT_MNEM_OK:
	LD	(FMT_CASE_MNEM),A
	JP	BT_CFG_LOOP

BT_TOGGLE_OPER:
	LD	A,(FMT_CASE_OPER)
	INC	A
	CP	3
	JR	C,BT_OPER_OK
	XOR	A
BT_OPER_OK:
	LD	(FMT_CASE_OPER),A
	JP	BT_CFG_LOOP

BT_TOGGLE_ANIM:
	LD	A,(FMT_ANIMATE)
	XOR	1
	LD	(FMT_ANIMATE),A
	JP	BT_CFG_LOOP

BT_CFG_SAVE_EXIT:
	CALL	SAVE_PLUGIN_CFG

BT_CFG_DONE:
	XOR	A			; A = 0: Clean, document unmodified
	OR	A			; Clear Carry
	RET

;------------------------------------------------------------------------------
; DO_ANIM_STEP: Check ESC cancel & update status bar ticker
; Returns Carry = 1 if ESC was pressed (abort), Carry = 0 otherwise
;------------------------------------------------------------------------------
DO_ANIM_STEP:
	; Check if key pressed via HOST_CHECK_KEY (IX+46)
	CALL	CALL_HOST_CHECKKEY
	JR	Z,ANIM_TICK_PROGRESS
	CALL	CALL_HOST_GETKEY
	CP	27			; ESC
	JR	Z,ANIM_ESC_HIT

ANIM_TICK_PROGRESS:
	; Check if tick threshold (every 32 lines or first line)
	LD	HL,(CUR_ROW_VAL)
	LD	A,L
	AND	1FH
	JR	NZ,ANIM_DONE

	; Format status ticker: "[Beautify: X/Y]"
	LD	DE,STR_TICK_BUF
	LD	HL,STR_TICK_PRE
	CALL	COPY_STR_Z_LOCAL
	LD	HL,(CUR_ROW_VAL)
	INC	HL
	CALL	FORMAT_DEC_5_DE
	LD	A,'/'
	LD	(DE),A
	INC	DE
	LD	HL,(BEAUTIFY_END_ROW)
	INC	HL
	CALL	FORMAT_DEC_5_DE
	LD	A,']'
	LD	(DE),A
	INC	DE
	XOR	A
	LD	(DE),A

	LD	DE,STR_TICK_BUF
	CALL	CALL_HOST_STATUS

ANIM_DONE:
	OR	A			; Carry = 0
	RET

ANIM_ESC_HIT:
	SCF				; Carry = 1
	RET

;==============================================================================
; BEAUTIFY_LINE_BUFFER: Realigns columns and normalizes case in ACTIVE_LINE_BUF
; Uses local LINE_OUTPUT_BUF
;==============================================================================
BEAUTIFY_LINE_BUFFER:
	PUSH	BC
	PUSH	DE
	PUSH	HL

	LD	HL,(HOST_ACTIVE_LINE_BUF)
	LD	DE,LINE_OUTPUT_BUF
	LD	C,1			; C = current 1-based column

	; 1. Check if line starts with whitespace
	LD	A,(HL)
	CP	' '
	JP	Z,BLB_NO_LABEL
	CP	9
	JP	Z,BLB_NO_LABEL
	CP	';'
	JP	Z,BLB_COL1_COMMENT
	OR	A
	JP	Z,BLB_BLANK_LINE

	; Line has a LABEL starting at col 1!
	LD	A,(FMT_LABEL_COL_CNT)
	CP	1
	JR	NZ,BLB_PAD_LABEL_COL
	LD	A,(FMT_LABEL_COL_MOD)
	CP	1
	JR	Z,BLB_LABEL_LOOP
BLB_PAD_LABEL_COL:
	PUSH	HL
	LD	IX,FMT_LABEL_COL_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL

BLB_LABEL_LOOP:
	LD	A,(HL)
	OR	A
	JR	Z,BLB_LABEL_END
	CP	':'
	JR	Z,BLB_LABEL_END
	CP	' '
	JR	Z,BLB_LABEL_END
	CP	9
	JR	Z,BLB_LABEL_END
	CP	';'
	JR	Z,BLB_LABEL_END
	; Apply label casing
	LD	A,(FMT_CASE_LABL)
	LD	B,A
	LD	A,(HL)
	CALL	APPLY_CASE
	LD	(DE),A
	INC	HL
	INC	DE
	INC	C
	JR	BLB_LABEL_LOOP

BLB_LABEL_END:
	; Check if original label had a colon
	LD	A,(HL)
	CP	':'
	JR	NZ,BLB_LBL_NO_COLON
	INC	HL			; skip original colon
	LD	B,1			; original_has_colon = 1
	JR	BLB_LBL_CHECK_COLON_RULE
BLB_LBL_NO_COLON:
	LD	B,0			; original_has_colon = 0

BLB_LBL_CHECK_COLON_RULE:
	LD	A,(FMT_LABEL_COLON)
	CP	':'
	JR	Z,BLB_LBL_EMIT_COLON
	CP	'-'
	JR	Z,BLB_LBL_SKIP_COLON
	CP	'?'
	JR	NZ,BLB_LBL_EMIT_COLON
	; '?' rule: preserve original colon
	LD	A,B
	OR	A
	JR	Z,BLB_LBL_SKIP_COLON
BLB_LBL_EMIT_COLON:
	LD	A,':'
	LD	(DE),A
	INC	DE
	INC	C
BLB_LBL_SKIP_COLON:

	; Label is done. Skip any whitespace after label
BLB_SKIP_WS_AFTER_LABEL:
	LD	A,(HL)
	CP	' '
	JR	Z,BLB_SWAL_INC
	CP	9
	JR	NZ,BLB_CHECK_AFTER_LABEL
BLB_SWAL_INC:
	INC	HL
	JR	BLB_SKIP_WS_AFTER_LABEL

BLB_CHECK_AFTER_LABEL:
	LD	A,(HL)
	OR	A
	JP	Z,BLB_FINISH_LINE
	CP	';'
	JP	Z,BLB_DO_COMMENT

	; Mnemonic follows label: Emit Sep_Mnem
	PUSH	HL
	LD	IX,FMT_STMT_MNEM_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL
	JR	BLB_DO_OPCODE_TOKEN

BLB_NO_LABEL:
	; Skip leading whitespace
BLB_SKIP_LEADING_WS:
	LD	A,(HL)
	CP	' '
	JR	Z,BLB_SLW_INC
	CP	9
	JR	NZ,BLB_CHECK_NO_LABEL
BLB_SLW_INC:
	INC	HL
	JR	BLB_SKIP_LEADING_WS

BLB_CHECK_NO_LABEL:
	LD	A,(HL)
	OR	A
	JP	Z,BLB_BLANK_LINE
	CP	';'
	JR	Z,BLB_INDENTED_COMMENT
	; Has mnemonic, no label:
	PUSH	HL
	LD	IX,FMT_STMT_MNEM_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL
	JR	BLB_DO_OPCODE_TOKEN

BLB_COL1_COMMENT:
	LD	A,(FMT_COMM_COL1_MOD)
	OR	A
	JR	Z,BLB_COPY_ORIG_LINE
	; 1 = align to mnemonic column
	PUSH	HL
	LD	IX,FMT_STMT_MNEM_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL
	JP	BLB_COMMENT_LOOP

BLB_INDENTED_COMMENT:
	LD	A,(FMT_COMM_IND_MOD)
	CP	'P'
	JR	Z,BLB_COPY_ORIG_LINE	; 'P' = preserve original
	; 'M' = align to mnemonic column
	PUSH	HL
	LD	IX,FMT_STMT_MNEM_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL
	JP	BLB_COMMENT_LOOP

BLB_COPY_ORIG_LINE:
	LD	HL,(HOST_ACTIVE_LINE_BUF)
	LD	DE,LINE_OUTPUT_BUF
BLB_COPY_ORIG_LOOP:
	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	OR	A
	JR	NZ,BLB_COPY_ORIG_LOOP
	JP	BLB_COMPARE_AND_RETURN

BLB_BLANK_LINE:
	XOR	A
	LD	(DE),A
	JP	BLB_COMPARE_AND_RETURN

BLB_DO_OPCODE_TOKEN:
	; Measure mnemonic length to check if directive
	PUSH	HL
	LD	B,0
BLB_MNEM_LEN_LOOP:
	LD	A,(HL)
	OR	A
	JR	Z,BLB_GOT_MNEM_LEN
	CP	' '
	JR	Z,BLB_GOT_MNEM_LEN
	CP	9
	JR	Z,BLB_GOT_MNEM_LEN
	CP	';'
	JR	Z,BLB_GOT_MNEM_LEN
	INC	HL
	INC	B
	JR	BLB_MNEM_LEN_LOOP

BLB_GOT_MNEM_LEN:
	POP	HL
	CALL	CHECK_IS_DIRECTIVE
	JR	C,BLB_IS_DIR
	LD	A,(FMT_CASE_MNEM)
	LD	(BLB_MNEM_CASE_TEMP),A
	JR	BLB_OPCODE_LOOP
BLB_IS_DIR:
	LD	A,(FMT_CASE_CNST)
	LD	(BLB_MNEM_CASE_TEMP),A

BLB_OPCODE_LOOP:
	LD	A,(HL)
	OR	A
	JP	Z,BLB_FINISH_LINE
	CP	';'
	JP	Z,BLB_DO_COMMENT
	CP	' '
	JR	Z,BLB_OPCODE_END
	CP	9
	JR	Z,BLB_OPCODE_END
	CALL	APPLY_CASE_CHAR
	LD	(DE),A
	INC	HL
	INC	DE
	INC	C
	JR	BLB_OPCODE_LOOP

BLB_OPCODE_END:
	; Skip whitespace between opcode and operands
BLB_SKIP_WS_AFTER_OPCODE:
	LD	A,(HL)
	CP	' '
	JR	Z,BLB_SWAO_INC
	CP	9
	JR	NZ,BLB_CHECK_AFTER_OPCODE
BLB_SWAO_INC:
	INC	HL
	JR	BLB_SKIP_WS_AFTER_OPCODE

BLB_CHECK_AFTER_OPCODE:
	LD	A,(HL)
	OR	A
	JP	Z,BLB_FINISH_LINE
	CP	';'
	JP	Z,BLB_DO_COMMENT

	; Operands follow! Emit Sep_Op1
	PUSH	HL
	LD	IX,FMT_STMT_OP1_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL

	; Copy operands with quote tracking and comma separator
	LD	B,0			; B = quote char (0 = none)
	XOR	A
	LD	(PREV_WAS_ID_CHAR),A
BLB_OPERAND_LOOP:
	LD	A,(HL)
	OR	A
	JR	Z,BLB_OPERAND_TRIM
	; Check if ';' outside quotes
	LD	A,B
	OR	A
	LD	A,(HL)
	JR	NZ,BLB_OP_INSIDE_QUOTE
	CP	';'
	JR	Z,BLB_OPERAND_TRIM
	; Check for quote start
	CP	27H			; '\''
	JR	Z,BLB_OP_START_QUOTE
	CP	22H			; '\"'
	JR	Z,BLB_OP_START_QUOTE

	; Check for comma ','
	CP	','
	JR	Z,BLB_OP_COMMA

	; Outside quotes: check if register casing applies
	LD	A,(PREV_WAS_ID_CHAR)
	OR	A
	JR	NZ,BLB_OP_CHECK_CHAR_CASE
	LD	A,B
	LD	(BLB_QUOTE_TEMP),A
	CALL	BLB_UPPERCASE_REG
	JR	NC,BLB_OP_NOT_REG
	LD	A,(BLB_QUOTE_TEMP)
	LD	B,A
	LD	A,1
	LD	(PREV_WAS_ID_CHAR),A
	JR	BLB_OPERAND_LOOP

BLB_OP_NOT_REG:
	LD	A,(BLB_QUOTE_TEMP)
	LD	B,A
BLB_OP_CHECK_CHAR_CASE:
	LD	A,(HL)
	JR	BLB_OP_COPY_CHAR

BLB_OP_COMMA:
	CALL	BLB_TRIM_TRAILING_SPACES
	LD	A,','
	LD	(DE),A
	INC	DE
	INC	C
	INC	HL
	; Skip whitespace after comma in (HL)
BLB_SKIP_WS_AFTER_COMMA:
	LD	A,(HL)
	CP	' '
	JR	Z,BLB_SWAC_INC
	CP	9
	JR	NZ,BLB_COMMA_EMIT_SEP
BLB_SWAC_INC:
	INC	HL
	JR	BLB_SKIP_WS_AFTER_COMMA
BLB_COMMA_EMIT_SEP:
	; Emit Sep_Op2
	PUSH	BC
	PUSH	HL
	LD	IX,FMT_STMT_OP2_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL
	POP	BC
	XOR	A
	LD	(PREV_WAS_ID_CHAR),A
	JR	BLB_OPERAND_LOOP

BLB_OP_START_QUOTE:
	LD	B,A			; Record quote char
	JR	BLB_OP_COPY_CHAR

BLB_OP_INSIDE_QUOTE:
	CP	B
	JR	NZ,BLB_OP_COPY_CHAR
	LD	B,0			; Quote closed

BLB_OP_COPY_CHAR:
	LD	(DE),A
	PUSH	AF
	CALL	IS_ID_CHAR_P
	LD	A,0
	JR	NC,BOC_NOT_ID
	INC	A
BOC_NOT_ID:
	LD	(PREV_WAS_ID_CHAR),A
	POP	AF
	INC	HL
	INC	DE
	INC	C
	JR	BLB_OPERAND_LOOP

BLB_OPERAND_TRIM:
	CALL	BLB_TRIM_TRAILING_SPACES

BLB_CHECK_AFTER_OPERAND:
	; Skip whitespace in HL to see if comment follows
BLB_SKIP_WS_AFTER_OPERAND:
	LD	A,(HL)
	CP	' '
	JR	Z,BLB_SWAOP_INC
	CP	9
	JR	NZ,BLB_CHECK_COMM_AFTER_OP
BLB_SWAOP_INC:
	INC	HL
	JR	BLB_SKIP_WS_AFTER_OPERAND

BLB_CHECK_COMM_AFTER_OP:
	LD	A,(HL)
	OR	A
	JP	Z,BLB_FINISH_LINE
	CP	';'
	JP	NZ,BLB_FINISH_LINE

BLB_DO_COMMENT:
	CALL	BLB_TRIM_TRAILING_SPACES
	; Pad to comment separator
	PUSH	HL
	LD	IX,FMT_STMT_COMM_CNT
	CALL	EMIT_FIELD_SEP
	POP	HL

	; Copy entire comment from (HL) to (DE)
BLB_COMMENT_LOOP:
	LD	A,(HL)
	OR	A
	JP	Z,BLB_FINISH_LINE
	CP	13
	JP	Z,BLB_FINISH_LINE
	CP	10
	JP	Z,BLB_FINISH_LINE
	LD	(DE),A
	INC	HL
	INC	DE
	JR	BLB_COMMENT_LOOP

BLB_FINISH_LINE:
	XOR	A
	LD	(DE),A

BLB_COMPARE_AND_RETURN:
	LD	HL,(HOST_ACTIVE_LINE_BUF)
	LD	DE,LINE_OUTPUT_BUF
BLB_CMP_LOOP:
	LD	A,(HL)
	LD	B,A
	LD	A,(DE)
	CP	B
	JR	NZ,BLB_IS_DIFFERENT
	OR	A
	JR	Z,BLB_IDENTICAL
	INC	HL
	INC	DE
	JR	BLB_CMP_LOOP

BLB_IS_DIFFERENT:
	; Copy formatted line back to ACTIVE_LINE_BUF
	LD	HL,LINE_OUTPUT_BUF
	LD	DE,(HOST_ACTIVE_LINE_BUF)
BLB_COPY_BACK:
	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	OR	A
	JR	NZ,BLB_COPY_BACK

	; Update line length in HOST_ACTIVE_LINE_LEN
	DEC	DE
	LD	HL,(HOST_ACTIVE_LINE_BUF)
	EX	DE,HL
	AND	A
	SBC	HL,DE			; HL = line byte length
	LD	DE,(HOST_ACTIVE_LINE_LEN)
	LD	A,L
	LD	(DE),A
	INC	DE
	LD	A,H
	LD	(DE),A

	; Setup args for HOST_COMMIT_LINE:
	; HL = line number, DE = buffer pointer, BC = line length
	LD	B,H
	LD	C,L			; BC = line length
	LD	HL,(CUR_ROW_VAL)	; HL = line number
	LD	DE,(HOST_ACTIVE_LINE_BUF) ; DE = buffer pointer

	; Commit line back to document via HOST_COMMIT_LINE (IX+21)
	CALL	CALL_HOST_COMMIT

	LD	A,1
	LD	(ANY_LINE_MODIFIED),A
	SCF				; Carry = 1 (modified)
	JR	BLB_EXIT

BLB_IDENTICAL:
	OR	A			; Carry = 0 (unmodified)

BLB_EXIT:
	POP	HL
	POP	DE
	POP	BC
	RET

; BLB_TRIM_TRAILING_SPACES: Trims any trailing spaces or tabs before DE in LINE_OUTPUT_BUF
BLB_TRIM_TRAILING_SPACES:
BLB_TRIM_LOOP:
	LD	A,C
	CP	2
	RET	C
	DEC	DE
	LD	A,(DE)
	CP	' '
	JR	Z,BLB_TRIM_DEC
	CP	9
	JR	Z,BLB_TRIM_DEC
	INC	DE
	RET
BLB_TRIM_DEC:
	DEC	C
	JR	BLB_TRIM_LOOP

; GET_NEXT_TAB_STOP: Input C = col (1-based), Output A = next tab stop
GET_NEXT_TAB_STOP:
	LD	A,C
	DEC	A
	LD	HL,CFG_TAB_MASK
	OR	(HL)
	ADD	A,2
	RET

; EMIT_FIELD_SEP: Emits separator according to 3-byte FieldSep (Count, Unit, Mode)
EMIT_FIELD_SEP:
	LD	A,(IX+2)		; Mode (0=Relative, 1=Absolute)
	OR	A
	JR	NZ,EFS_ABSOLUTE
	; Relative Mode:
	LD	B,(IX+0)		; Count
	LD	A,B
	OR	A
	RET	Z			; Count = 0 -> nothing to emit
	LD	A,(IX+1)		; Unit (0=space, 1=tab)
	OR	A
	JR	NZ,EFS_REL_TAB
EFS_REL_SPACE:
	LD	A,' '
	LD	(DE),A
	INC	DE
	INC	C
	DJNZ	EFS_REL_SPACE
	RET
EFS_REL_TAB:
	LD	A,9			; '\t'
	LD	(DE),A
	INC	DE
	CALL	GET_NEXT_TAB_STOP
	LD	C,A
	DJNZ	EFS_REL_TAB
	RET

EFS_ABSOLUTE:
	; Absolute Mode:
	LD	B,(IX+0)		; B = TargetCol
	LD	A,C
	CP	B
	JR	NC,EFS_ABS_OVERFLOW	; CurrentCol >= TargetCol -> Overflow!
	; CurrentCol < TargetCol
	LD	A,(IX+1)		; Unit (0=space, 1=tab)
	OR	A
	JR	NZ,EFS_ABS_TAB
EFS_ABS_SPACE:
	LD	A,' '
	LD	(DE),A
	INC	DE
	INC	C
	LD	A,C
	CP	B
	JR	C,EFS_ABS_SPACE
	RET
EFS_ABS_TAB:
EFS_TAB_LOOP:
	LD	A,C
	CP	B
	RET	NC			; If C >= TargetCol (B), done
	LD	A,9			; '\t'
	LD	(DE),A
	INC	DE
	CALL	GET_NEXT_TAB_STOP
	LD	C,A
	JR	EFS_TAB_LOOP

EFS_ABS_OVERFLOW:
	LD	A,(IX+1)		; Unit (0=space, 1=tab)
	OR	A
	JR	NZ,EFS_OVR_TAB
	LD	A,' '
	LD	(DE),A
	INC	DE
	INC	C
	RET
EFS_OVR_TAB:
	LD	A,9
	LD	(DE),A
	INC	DE
	CALL	GET_NEXT_TAB_STOP
	LD	C,A
	RET

